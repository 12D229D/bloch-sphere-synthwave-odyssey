/**
 * qasm-exporter.js / qasm-pulse-exporter.js
 * Compilador de pulsos continuos y compuertas a OpenQASM 3.0 estándar
 * y scripts ejecutables de Google Cirq (Python).
 */

export class QasmExporter {
    constructor() {
        this.qubitName = 'q[0]';
    }

    /**
     * Exporta la secuencia de compuertas a formato OpenQASM 3.0
     */
    exportToOpenQASM(gatesHistory, options = {}) {
        const {
            qubitCount = 1,
            programName = 'BlochSphereSynthwaveOdysseyCircuit'
        } = options;

        let qasm = `// ========================================================\n`;
        qasm += `// Generated by Bloch Sphere Synthwave Odyssey (SU(2) Engine)\n`;
        qasm += `// OpenQASM 3.0 Standard Quantum Circuit Representation\n`;
        qasm += `// Target: Superconducting Microwave Qubit / Rabi Control\n`;
        qasm += `// ========================================================\n\n`;
        qasm += `OPENQASM 3.0;\n`;
        qasm += `include "stdgates.inc";\n\n`;
        qasm += `qubit[${qubitCount}] q;\n`;
        qasm += `bit[${qubitCount}] c;\n\n`;

        if (!gatesHistory || gatesHistory.length === 0) {
            qasm += `// No pulse gates executed in this run.\n`;
            qasm += `h q[0];\n`;
            qasm += `measure q[0] -> c[0];\n`;
            return qasm;
        }

        gatesHistory.forEach((item, idx) => {
            const timeStr = item.time ? ` // t = ${item.time.toFixed(2)}s` : '';
            const g = item.gate.toUpperCase();

            switch (g) {
                case 'X':
                    qasm += `x q[0];${timeStr}\n`;
                    break;
                case 'Y':
                    qasm += `y q[0];${timeStr}\n`;
                    break;
                case 'Z':
                    qasm += `z q[0];${timeStr}\n`;
                    break;
                case 'H':
                    qasm += `h q[0];${timeStr}\n`;
                    break;
                case 'S':
                    qasm += `s q[0];${timeStr}\n`;
                    break;
                case 'SDAG':
                    qasm += `s_dg q[0];${timeStr}\n`;
                    break;
                case 'T':
                    qasm += `t q[0];${timeStr}\n`;
                    break;
                case 'RX':
                    const thetaX = (item.strength || 1.0).toFixed(4);
                    qasm += `rx(${thetaX}) q[0];${timeStr}\n`;
                    break;
                case 'RY':
                    const thetaY = (item.strength || 1.0).toFixed(4);
                    qasm += `ry(${thetaY}) q[0];${timeStr}\n`;
                    break;
                case 'RZ':
                    const phiZ = (item.strength || 1.0).toFixed(4);
                    qasm += `rz(${phiZ}) q[0];${timeStr}\n`;
                    break;
                case 'SPINECHO':
                    qasm += `// --- Hahn Spin Echo Pi refocusing pulse ---\n`;
                    qasm += `x q[0];${timeStr}\n`;
                    break;
                default:
                    qasm += `// Unknown pulse: ${g}\n`;
                    break;
            }
        });

        qasm += `\n// Final readout measurement\n`;
        qasm += `c[0] = measure q[0];\n`;

        return qasm;
    }

    /**
     * Exporta la secuencia de compuertas a Google Cirq (Python)
     */
    exportToCirq(gatesHistory) {
        let py = `"""\n`;
        py += `Google Cirq Quantum Circuit - Bloch Sphere Synthwave Odyssey\n`;
        py += `Generated automatically from SU(2) microwave control pulses.\n`;
        py += `"""\n`;
        py += `import cirq\nimport numpy as np\n\n`;
        py += `def create_bloch_synthwave_circuit():\n`;
        py += `    q = cirq.LineQubit(0)\n`;
        py += `    circuit = cirq.Circuit()\n\n`;

        if (!gatesHistory || gatesHistory.length === 0) {
            py += `    circuit.append(cirq.H(q))\n`;
            py += `    circuit.append(cirq.measure(q, key='result'))\n`;
            py += `    return circuit\n\n`;
        } else {
            gatesHistory.forEach((item) => {
                const g = item.gate.toUpperCase();
                switch (g) {
                    case 'X':
                        py += `    circuit.append(cirq.X(q))\n`;
                        break;
                    case 'Y':
                        py += `    circuit.append(cirq.Y(q))\n`;
                        break;
                    case 'Z':
                        py += `    circuit.append(cirq.Z(q))\n`;
                        break;
                    case 'H':
                        py += `    circuit.append(cirq.H(q))\n`;
                        break;
                    case 'S':
                        py += `    circuit.append(cirq.S(q))\n`;
                        break;
                    case 'T':
                        py += `    circuit.append(cirq.T(q))\n`;
                        break;
                    case 'RX':
                        py += `    circuit.append(cirq.rx(${item.strength || 1.0})(q))\n`;
                        break;
                    case 'RY':
                        py += `    circuit.append(cirq.ry(${item.strength || 1.0})(q))\n`;
                        break;
                    case 'RZ':
                        py += `    circuit.append(cirq.rz(${item.strength || 1.0})(q))\n`;
                        break;
                    case 'SPINECHO':
                        py += `    # Hahn Spin Echo Refocusing\n`;
                        py += `    circuit.append(cirq.X(q))\n`;
                        break;
                }
            });
            py += `    circuit.append(cirq.measure(q, key='result'))\n`;
            py += `    return circuit\n\n`;
        }

        py += `if __name__ == '__main__':\n`;
        py += `    circuit = create_bloch_synthwave_circuit()\n`;
        py += `    print("=== Bloch Synthwave Circuit Diagram ===")\n`;
        py += `    print(circuit)\n`;
        py += `    sim = cirq.Simulator()\n`;
        py += `    results = sim.run(circuit, repetitions=1000)\n`;
        py += `    print("\\nSimulation histogram:")\n`;
        py += `    print(results.histogram(key='result'))\n`;

        return py;
    }
}
